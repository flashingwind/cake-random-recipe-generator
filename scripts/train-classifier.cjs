const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {fit,predict}=require('../classifier.js');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const anchors=vm.runInNewContext(html.match(/const ANCHORS = (\[[\s\S]*?\n\]);/)[0]+'; ANCHORS');
const bases=anchors.filter(a=>!a.id.endsWith('-home'));
const categories=new Map(bases.map(a=>[a.name,a]));
const recipes=JSON.parse(fs.readFileSync(path.join(root,'data/recipes.json'),'utf8')).recipes;
const seen=new Set();
const ids=new Set();
const publicRows=recipes.map(r=>{
  const category=categories.get(r.category);
  if(!category || !r.source?.url)throw Error('Unknown category or missing source: '+r.id);
  if(ids.has(r.id))throw Error('Duplicate id: '+r.id);
  ids.add(r.id);
  const key=JSON.stringify([r.source.url,r.category,...['fat','egg','sugar','liquid','bp'].map(k=>r[k])]);
  if(seen.has(key))return null;
  seen.add(key);
  return {...r,color:category.color,method:r.method||category.method,profile:r.profile||'home',kind:'public-recipe'};
}).filter(Boolean);
const seeds=anchors.map(a=>({...a,category:bases.find(b=>b.id===a.id.replace(/-home$/,'')).name,
  profile:a.id.endsWith('-home')?'home':'standard',kind:'anchor-estimate'}));
const model=fit([...publicRows,...seeds]);
// Evaluate public recipes by holding out the entire source host. Anchor estimates
// are excluded so aggregates derived from this dataset cannot leak into validation.
const hosts=[...new Set(publicRows.map(r=>new URL(r.source.url).hostname))];
const predictions=[];
for(const host of hosts){
  const train=publicRows.filter(r=>new URL(r.source.url).hostname!==host);
  const fold=fit(train);
  for(const row of publicRows.filter(r=>new URL(r.source.url).hostname===host)){
    const result=predict(fold,row);predictions.push({id:row.id,expected:row.category,predicted:result.category,heldOutHost:host});
  }
}
const correct=predictions.filter(r=>r.expected===r.predicted).length;
const counts=Object.fromEntries(bases.map(a=>[a.name,publicRows.filter(r=>r.category===a.name).length]));
const report={method:'leave-one-source-host-out; public recipes only; no anchor estimates',features:model.features,k:model.k,
  publicRecipes:publicRows.length,anchorEstimates:seeds.length,counts,evaluated:predictions.length,correct,
  accuracy:correct/predictions.length,limitations:['Only categories with public recipes are evaluated.','Source URLs and ingredient conversions are inherited data, not reverified by training.','Home/standard labels have no held-out validation.','Anchor-only categories are provisional.'],predictions};
model.summary={publicRecipes:publicRows.length,anchorEstimates:seeds.length,counts};
fs.writeFileSync(path.join(root,'data/classifier-model.js'),'// Generated by node scripts/train-classifier.cjs\nglobalThis.RECIPE_MODEL = '+JSON.stringify(model,null,2)+';\n');
fs.writeFileSync(path.join(root,'data/classifier-evaluation.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({publicRecipes:report.publicRecipes,anchorEstimates:report.anchorEstimates,counts,evaluated:report.evaluated,correct,accuracy:report.accuracy},null,2));
