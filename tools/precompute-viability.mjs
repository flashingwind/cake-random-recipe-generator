// Run: node tools/precompute-viability.mjs
// Regenerates the grid from the SAME judge() used by the website.
import { readFileSync, writeFileSync } from 'node:fs';
const index=readFileSync(new URL('../index.html',import.meta.url),'utf8');
function part(from,to){
  const start=index.indexOf(from);
  const end=index.indexOf(to,start);
  if(start<0||end<0)throw new Error('Could not find '+from);
  return index.slice(start,end);
}
const anchors=part('const ANCHORS = [','// 境界カテゴリ');
const categories=part('const DISPLAY_CATEGORIES =','const DISPLAY_ANCHORS =');
const judgeCode=part('function riseModel(s){','// ===== 最寄り基準点');
const build=new Function(anchors+categories+judgeCode+`
const classes=DISPLAY_CATEGORIES;
const bases=classes.map(name=>ANCHORS.filter(a=>
  a.name===name||a.name.startsWith(name.replace('ケーキ','')+'（家庭用）')));
const data=new Uint8Array(12*43*41),count=Array(7).fill(0);
for(let fi=0;fi<12;fi++)for(let ei=0;ei<43;ei++)for(let li=0;li<41;li++){
  const fat=fi*10,egg=ei*10,liquid=li*10;
  let bits=0;
  for(let ci=0;ci<classes.length;ci++){
    let found=false;
    for(const anchor of bases[ci]){
      const fatTypes=fat===0?['none']:anchor.fatType==='none'
        ?['butter','oil']:[anchor.fatType];
      for(const fatType of fatTypes){
        for(let sugar=0;sugar<=200;sugar+=10){
          for(const bpOn of [false,true]){
            const candidate={...anchor,fat,egg,liquid,sugar,fatType,bp:bpOn?1:0};
            if(judge(candidate,classes[ci]).worst!=='bad'){found=true;break;}
          }
          if(found)break;
        }
        if(found)break;
      }
      if(found)break;
    }
    if(found){bits|=1<<ci;count[ci]++;}
  }
  data[(fi*43+ei)*41+li]=bits;
}
return {classes,data,count};
`);
const {classes,data,count}=build();
const hex=[...data].map(v=>v.toString(16).padStart(2,'0')).join('');
const output=`// Generated by tools/precompute-viability.mjs. Do not edit manually.
// 10 g grid, flour 100 g; each bit is a category with at least one
// successful sugar (0..200 g), BP ON/OFF and reference-method combination.
(function(root){
  root.CAKE_VIABILITY_GRID={
    axes:{fat:{min:0,step:10,count:12},egg:{min:0,step:10,count:43},liquid:{min:0,step:10,count:41}},
    categories:${JSON.stringify(classes)},
    encoding:'hex-u8',data:'${hex}'
  };
})(globalThis);
`;
writeFileSync(new URL('../data/viability-grid.js',import.meta.url),output);
process.stdout.write(JSON.stringify({gridPoints:data.length,viableCellsByCategory:count})+'\\n');
